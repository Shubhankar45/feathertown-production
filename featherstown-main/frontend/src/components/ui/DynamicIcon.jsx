export default function DynamicIcon({
  name,
  size = 18,
  strokeWidth = 2,
  color,
  className = "",
  style = {},
  ...props
}) {
  if (!name) return null;

  const key = typeof name === "string" ? name.toLowerCase().trim() : "";
  const IconComponent = ICON_MAP[key] || ICON_MAP[name] || Feather;

  return (
    <IconComponent
      size={size}
      strokeWidth={strokeWidth}
      color={color}
      className={className}
      style={{ flexShrink: 0, display: "inline-block", verticalAlign: "middle", ...style }}
      {...props}
    />
  );
}

