/**
 * Returns a parrot avatar image path.
 * If an explicit avatar or path is passed, returns that.
 * If no avatar is passed, deterministically selects a parrot based on the seed string (e.g. user name).
 */
export function getAvatarPath(avatarIdOrPath, seed = "") {
  if (avatarIdOrPath) {
    const match = BIRD_AVATARS.find(
      (a) =>
        a.id === avatarIdOrPath ||
        a.path === avatarIdOrPath ||
        (avatarIdOrPath.includes(a.id) && avatarIdOrPath.endsWith(".svg"))
    );
    if (match) return match.path;
    if (avatarIdOrPath.startsWith("http") || avatarIdOrPath.startsWith("/")) {
      return avatarIdOrPath;
    }
  }

  // Deterministic fallback based on seed string
  const str = String(seed || "featherstown").trim();
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  const idx = Math.abs(hash) % BIRD_AVATARS.length;
  return BIRD_AVATARS[idx].path;
}

export function getAvatarMeta(avatarIdOrPath) {
  if (!avatarIdOrPath) return null;
  return (
    BIRD_AVATARS.find(
      (a) =>
        a.id === avatarIdOrPath ||
        a.path === avatarIdOrPath ||
        (avatarIdOrPath.includes(a.id) && avatarIdOrPath.endsWith(".svg"))
    ) || null
  );
}
